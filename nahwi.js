// «أعرب الكلمة»: خطوات النوع ← الموقع ← العلامة
const TYPE_N = { ism: "اسم", fiel: "فعل", harf: "حرف" };
function irabItem(it) {
  const steps = [{ k: "t", q: "ما نوع الكلمة؟", o: ["اسم", "فعل", "حرف"], a: TYPE_N[it.t] }];
  if (it.t !== "harf") {
    const pool = it.t === "fiel" ? ["فعل مضارع", "فعل ماضٍ", "فعل أمر"] : POS.filter((x) => !/^فعل|^حرف/.test(x));
    steps.push({ k: "p", q: it.t === "fiel" ? "ما نوع الفعل؟" : "ما موقعها في الجملة؟", o: shuffle([it.p, ...shuffle(pool.filter((x) => x !== it.p)).slice(0, it.t === "fiel" ? 2 : 3)]), a: it.p });
  }
  steps.push({ k: "m", q: it.m === "مبني" ? "هل هي معربة أم مبنية؟" : "ما علامة إعرابها؟", o: shuffle([it.m, ...shuffle(MARKS.filter((x) => x !== it.m)).slice(0, 3)]), a: it.m });
  return { it, steps, s: 0, pick: null, ok: true };
}
