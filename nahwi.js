function click(el, api) {
  A = api; st();
  const a = el.dataset.a, r = api.top();
  const R = run;
  switch (a) {
    case "mode": S.mode = el.dataset.m; save(); api.refresh(false); break;
    case "home": run = null; api.back(); break;
    case "lesson": run = null; (el.dataset.rep ? api.replace : api.push)({ v: "nahwiL", i: +el.dataset.i }); break;
    case "game": run = null; api.push({ v: "nahwiG", k: el.dataset.k }); break;
    case "w": {
      const i = r.i, x = +el.dataset.x, y = +el.dataset.y;
      sel[i + ":" + x] = y; speak(LESSONS[i].examples[x][y][0]); api.refresh(false); break;
    }
    case "sayEx": speak(LESSONS[r.i].examples[+el.dataset.x].map((w) => w[0]).join(" ")); break;
    case "opt": {
      if (!R || R.picked !== null) break;
      const q = R.qs[R.k];
      R.picked = +el.dataset.i;
      if (R.picked === q.a) { R.score++; gain(1); if (q.ref && S.miss[q.ref]) { delete S.miss[q.ref]; S.fixed++; save(); } }
      else if (q.ref) { S.miss[q.ref] = Date.now(); save(); }
      api.refresh(false); break;
    }
    case "next": {
      if (!R) break;
      R.k++; R.picked = null;
      if (R.k >= R.qs.length && r.v === "nahwiL") {
        const l = LESSONS[r.i], n = l.quiz.length, s = R.score === n ? 3 : R.score >= n / 2 ? 2 : 1;
        R.stars = s;
        const first = !S.done[l.id];
        if (!S.done[l.id] || S.done[l.id] < s) S.done[l.id] = s;
        save();
        if (first && api.syncLesson) api.syncLesson("nh:" + l.id);
      }
      if (R.k >= R.qs.length && R.score === R.qs.length) api.toast(kids() ? "🎉 ⭐ ⭐ ⭐" : "🎉 إتقان تام");
      api.refresh(false); break;
    }
    case "again": run = null; api.refresh(false); break;
    case "bin": {
      if (!R || R.ans !== null) break;
      R.ans = el.dataset.t; if (R.ans === R.words[R.k][1]) { R.score++; gain(1); }
      api.refresh(false); break;
    }
    case "sortNext": R.k++; R.ans = null; api.refresh(false); if (R.k < R.words.length) speak(R.words[R.k][0]); break;
    case "chip": R.ans.push(R.pool.splice(+el.dataset.i, 1)[0]); api.refresh(false); break;
    case "unchip": R.pool.push(R.ans.splice(+el.dataset.i, 1)[0]); api.refresh(false); break;
    case "check": {
      const item = R.list[R.k], s = R.ans.map((p) => p.w).join(" ");
      R.checked = [item.w, ...(item.alt || [])].some((o) => o.join(" ") === s);
      if (R.checked) { R.score++; gain(1); }
      speak(item.w.join(" ")); api.refresh(false); break;
    }
    case "buildNext": R.k++; if (R.k < R.list.length) Object.assign(R, newBuild(R.list[R.k])); api.refresh(false); break;
    case "irabPick": {
      const X = R.items[R.k], stp = X.steps[X.s];
      if (X.pick !== null) break;
      X.pick = +el.dataset.i;
      if (stp.o[X.pick] !== stp.a) X.ok = false;
      api.refresh(false); break;
    }
    case "irabStep": {
      const X = R.items[R.k]; X.s++; X.pick = null;
      if (X.s >= X.steps.length) { if (X.ok) { R.score++; S.irab++; gain(2); } speak(X.it.s.join(" ")); }
      api.refresh(false); break;
    }
    case "irabNext": R.k++; api.refresh(false); break;
  }
  return true;
}
